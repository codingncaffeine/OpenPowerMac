// Transcribed from:
//   - MPC7400/MPC7410 RISC Microprocessor User's Manual, Appendix A
//     (instruction set listings sorted by opcode) and §2.3
//   - Programming Environments Manual (MPCFPE32B), Appendix A
//   - AltiVec Technology Programming Environments Manual, opcode appendix
//
// The 7400 implements every 32-bit PowerPC instruction except fsqrt, fsqrts
// and tlbia (UM §2.3: attempting those raises the illegal-instruction program
// exception) — those three rows carry FL_ILL7400 so the disassembler still
// names them while execution faults authentically.

